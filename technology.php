    <h1>Технологии и стандарты связи в Марокко</h1>
    <p class="last-updated">Обновлено: октябрь 2026</p>

    <p>Телекоммуникационная инфраструктура Марокко построена на общепринятых международных стандартах, что обеспечивает совместимость с абсолютным большинством мобильных устройств, произведённых для европейского, ближневосточного и африканского рынков. В этом разделе рассмотрены все поколения мобильной связи, используемые в стране, их частотные характеристики и перспективы развития.</p>

    <h2>2G &mdash; GSM</h2>

    <p>Сети второго поколения были развёрнуты в Марокко в середине 1990-х годов и до сих пор остаются фундаментом мобильной инфраструктуры страны. Стандарт GSM работает в двух частотных диапазонах:</p>

    <table class="spec-table">
        <tr><th>Диапазон</th><th>Частоты</th><th>Применение</th></tr>
        <tr><td>GSM 900</td><td>890&ndash;960 МГц</td><td>Основной диапазон, обеспечивает широкое территориальное покрытие благодаря хорошему проникновению сигнала</td></tr>
        <tr><td>GSM 1800</td><td>1710&ndash;1880 МГц</td><td>Дополнительный диапазон для увеличения ёмкости в городских зонах</td></tr>
    </table>

    <p>Сети GSM обеспечивают голосовую связь и передачу SMS на всей территории Марокко, включая отдалённые районы Атласских гор и окраины Сахары. Технологии GPRS и EDGE, надстроенные над GSM, позволяют осуществлять базовую передачу данных, хотя их скорость ограничена сотнями килобит в секунду.</p>

    <h2>3G &mdash; UMTS / HSPA+</h2>

    <p>Третье поколение мобильной связи на основе стандарта UMTS было запущено в Марокко в 2007 году. Сети 3G работают в диапазоне 2100 МГц (Band 1) &mdash; общемировом стандартном диапазоне для UMTS.</p>

    <p>Развитие технологии шло поэтапно:</p>

    <ul>
        <li><strong>UMTS (R99)</strong> &mdash; начальное развёртывание, скорость до 384 Кбит/с.</li>
        <li><strong>HSDPA</strong> &mdash; модернизация канала «от сети к абоненту», скорость до 14,4 Мбит/с.</li>
        <li><strong>HSPA+</strong> &mdash; дальнейшее улучшение, теоретическая скорость до 42 Мбит/с в канале загрузки.</li>
    </ul>

    <p>К настоящему времени сети 3G покрывают большую часть населённой территории Марокко. Они остаются важным резервным уровнем связи в районах, где сигнал 4G недоступен или нестабилен. При этом операторы постепенно перераспределяют спектр 3G в пользу более эффективных технологий 4G.</p>

    <h2>4G &mdash; LTE / LTE-Advanced</h2>

    <p>Коммерческий запуск сетей четвёртого поколения в Марокко состоялся в апреле 2015 года. Все три оператора получили лицензии на использование нескольких частотных диапазонов для LTE:</p>

    <table class="spec-table">
        <tr><th>Диапазон</th><th>Полоса 3GPP</th><th>Характеристики</th></tr>
        <tr><td>800 МГц</td><td>Band 20</td><td>Низкочастотный диапазон с отличным проникновением в здания и большим радиусом действия базовой станции. Используется для покрытия пригородных и сельских территорий.</td></tr>
        <tr><td>1800 МГц</td><td>Band 3</td><td>Средний диапазон, баланс между ёмкостью и покрытием. Основная рабочая частота LTE в городах.</td></tr>
        <tr><td>2600 МГц</td><td>Band 7</td><td>Высокочастотный диапазон с максимальной ёмкостью, но ограниченным радиусом. Применяется в центрах крупных городов и местах массового скопления людей.</td></tr>
    </table>

    <p>Операторы активно применяют технологию агрегации несущих (Carrier Aggregation, CA), объединяя два или три диапазона для увеличения скорости передачи данных. В результате в крупных городах реальная скорость мобильного интернета может достигать 100&ndash;150 Мбит/с.</p>

    <div class="info-box">
        <p>Технология LTE-Advanced Pro (4.5G) внедряется операторами для повышения пиковых скоростей и снижения задержек. Она служит переходной ступенью к полноценному 5G и уже доступна в отдельных районах Касабланки и Рабата.</p>
    </div>

    <h2>5G &mdash; текущее состояние и перспективы</h2>

    <p>Развёртывание сетей пятого поколения в Марокко находится на начальной стадии. Регулятор ANRT выделил частотный ресурс для 5G и провёл тендерные процедуры. Основные диапазоны, рассматриваемые для 5G в Марокко:</p>

    <ul>
        <li><strong>3,5 ГГц (n78)</strong> &mdash; основной диапазон для городского покрытия 5G. Обеспечивает баланс между ёмкостью и зоной обслуживания базовой станции.</li>
        <li><strong>700 МГц (n28)</strong> &mdash; низкочастотный диапазон для обширного территориального покрытия. Предполагается использование для сельских и пригородных территорий.</li>
        <li><strong>26 ГГц (n258)</strong> &mdash; миллиметровый диапазон для сверхвысоких скоростей в ограниченных зонах (стадионы, транспортные узлы, деловые кварталы).</li>
    </ul>

    <p>Пилотные проекты 5G реализуются в деловых кварталах Касабланки и административном центре Рабата. Массовое коммерческое развёртывание ожидается поэтапно, начиная с крупнейших городов и постепенно охватывая региональные центры.</p>

    <h2>Международный роуминг</h2>

    <p>Марокко интегрировано в глобальную систему международного роуминга. Все три оператора имеют роуминговые соглашения с сотнями операторов по всему миру, обеспечивая возможность использования мобильных устройств иностранными посетителями.</p>

    <h3>Общие принципы работы роуминга в Марокко</h3>

    <p>При въезде в страну мобильное устройство автоматически регистрируется в сети одного из марокканских операторов, если у домашнего оператора абонента есть соответствующее роуминговое соглашение. Выбор сети происходит автоматически, но может быть изменён вручную в настройках устройства.</p>

    <p>Поскольку Марокко использует европейские стандарты GSM/UMTS/LTE, устройства, приобретённые в Европе, России, странах СНГ и большинстве азиатских стран, полностью совместимы с марокканскими сетями. Устройства, рассчитанные исключительно на стандарт CDMA (некоторые модели для рынка США), могут не работать.</p>

    <h3>Технические особенности роуминга</h3>

    <ul>
        <li>Роуминг 2G (GSM) поддерживается всеми операторами и доступен практически на всей территории страны.</li>
        <li>Роуминг 3G (UMTS) работает в основных городах и вдоль автомагистралей.</li>
        <li>Роуминг 4G (LTE) доступен при наличии соглашения между домашним и марокканским оператором; не все операторы предоставляют LTE-роуминг.</li>
        <li>VoLTE-роуминг (голосовая связь через LTE) поддерживается ограниченным числом пар операторов.</li>
    </ul>

    <div class="info-box">
        <p>Для корректной работы в роуминге рекомендуется включить опцию «Роуминг данных» в настройках устройства и убедиться, что APN-настройки установлены автоматически. Режим выбора сети лучше оставить автоматическим &mdash; ручной выбор может привести к подключению к сети без роумингового соглашения.</p>
    </div>


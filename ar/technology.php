    <h1>تقنيات ومعايير الاتصالات في المغرب</h1>
    <p class="last-updated">آخر تحديث: أكتوبر 2026</p>

    <p>تستند البنية التحتية للاتصالات في المغرب إلى المعايير الدولية المعتمدة، مما يضمن التوافق مع الغالبية العظمى من الأجهزة المحمولة المُصنّعة للأسواق الأوروبية والشرق أوسطية والأفريقية.</p>

    <h2>الجيل الثاني — GSM</h2>
    <p>نُشرت شبكات الجيل الثاني في المغرب في منتصف التسعينيات ولا تزال تُشكّل ركيزة البنية التحتية للهاتف المحمول. يعمل معيار GSM على نطاقي تردد:</p>
    <table class="spec-table">
        <tr><th>النطاق</th><th>الترددات</th><th>الاستخدام</th></tr>
        <tr><td>GSM 900</td><td>890–960 ميغاهرتز</td><td>النطاق الرئيسي الذي يوفر تغطية واسعة بفضل اختراق جيد للإشارة</td></tr>
        <tr><td>GSM 1800</td><td>1710–1880 ميغاهرتز</td><td>نطاق تكميلي لزيادة السعة في المناطق الحضرية</td></tr>
    </table>
    <p>توفر شبكات GSM الاتصالات الصوتية وإرسال الرسائل القصيرة عبر كامل التراب المغربي، بما في ذلك المناطق النائية في جبال الأطلس وأطراف الصحراء.</p>

    <h2>الجيل الثالث — UMTS / HSPA+</h2>
    <p>أُطلق الجيل الثالث القائم على معيار UMTS في المغرب عام 2007، ويعمل على نطاق 2100 ميغاهرتز (Band 1).</p>
    <p>تطوّرت التقنية على مراحل:</p>
    <ul>
        <li><strong>UMTS (R99)</strong> — النشر الأولي، سرعة تصل إلى 384 كيلوبت/ثانية.</li>
        <li><strong>HSDPA</strong> — تحسين قناة التحميل، سرعة تصل إلى 14.4 ميغابت/ثانية.</li>
        <li><strong>HSPA+</strong> — تحسين إضافي، سرعة نظرية تصل إلى 42 ميغابت/ثانية.</li>
    </ul>
    <p>تغطي شبكات الجيل الثالث حاليًا معظم المناطق المأهولة في المغرب. وتظل مستوى احتياطيًا مهمًا في المناطق التي لا تتوفر فيها تغطية الجيل الرابع.</p>

    <h2>الجيل الرابع — LTE / LTE-Advanced</h2>
    <p>أُطلقت شبكات الجيل الرابع تجاريًا في المغرب في أبريل 2015. حصل المشغّلون الثلاثة على تراخيص لاستخدام عدة نطاقات ترددية:</p>
    <table class="spec-table">
        <tr><th>النطاق</th><th>نطاق 3GPP</th><th>الخصائص</th></tr>
        <tr><td>800 ميغاهرتز</td><td>Band 20</td><td>نطاق منخفض التردد مع اختراق ممتاز للمباني ومدى واسع. يُستخدم لتغطية المناطق شبه الحضرية والريفية.</td></tr>
        <tr><td>1800 ميغاهرتز</td><td>Band 3</td><td>نطاق متوسط، توازن بين السعة والتغطية. التردد الرئيسي لعمل LTE في المدن.</td></tr>
        <tr><td>2600 ميغاهرتز</td><td>Band 7</td><td>نطاق عالي التردد بسعة قصوى لكن بمدى محدود. يُستخدم في مراكز المدن الكبرى وأماكن التجمّعات.</td></tr>
    </table>
    <p>يستخدم المشغّلون بنشاط تقنية تجميع الحاملات (Carrier Aggregation)، حيث يجمعون نطاقين أو ثلاثة لزيادة سرعة نقل البيانات. ونتيجة لذلك، يمكن أن تصل السرعة الفعلية للإنترنت المحمول في المدن الكبرى إلى 100-150 ميغابت/ثانية.</p>

    <div class="info-box">
        <p>يُنشر المشغّلون تقنية LTE-Advanced Pro (4.5G) لرفع السرعات القصوى وخفض زمن الاستجابة. وتُعدّ مرحلة انتقالية نحو الجيل الخامس الكامل، وهي متاحة بالفعل في بعض أحياء الدار البيضاء والرباط.</p>
    </div>

    <h2>الجيل الخامس — الوضع الراهن والآفاق</h2>
    <p>يمر نشر شبكات الجيل الخامس في المغرب بمراحله الأولى. خصّصت الوكالة الوطنية لتقنين الاتصالات (ANRT) موارد ترددية للجيل الخامس. النطاقات الرئيسية المدروسة:</p>
    <ul>
        <li><strong>3.5 غيغاهرتز (n78)</strong> — النطاق الرئيسي للتغطية الحضرية بالجيل الخامس.</li>
        <li><strong>700 ميغاهرتز (n28)</strong> — نطاق منخفض التردد للتغطية الواسعة في المناطق الريفية وشبه الحضرية.</li>
        <li><strong>26 غيغاهرتز (n258)</strong> — نطاق الموجات المليمترية لسرعات فائقة في مناطق محدودة.</li>
    </ul>
    <p>تُنفّذ مشاريع تجريبية للجيل الخامس في أحياء الأعمال بالدار البيضاء والمركز الإداري بالرباط. يُنتظر النشر التجاري الشامل بشكل تدريجي، بدءًا من أكبر المدن ثم التوسع نحو المراكز الجهوية.</p>

    <h2>التجوال الدولي</h2>
    <p>المغرب مندمج في النظام العالمي للتجوال الدولي (الرومينغ). يمتلك المشغّلون الثلاثة اتفاقيات تجوال مع مئات المشغّلين حول العالم، مما يُتيح للزوار الأجانب استخدام أجهزتهم المحمولة.</p>

    <h3>مبادئ عمل التجوال في المغرب</h3>
    <p>عند الدخول إلى البلاد، يُسجّل الجهاز المحمول تلقائيًا على شبكة أحد المشغّلين المغاربة، شريطة وجود اتفاقية تجوال مع مشغّل المشترك الأصلي. يتم اختيار الشبكة تلقائيًا، ويمكن تغييره يدويًا في إعدادات الجهاز.</p>
    <p>نظرًا لاستخدام المغرب معايير GSM/UMTS/LTE الأوروبية، فإن الأجهزة المقتناة في أوروبا والشرق الأوسط ومعظم الدول الآسيوية متوافقة تمامًا مع الشبكات المغربية.</p>

    <h3>الجوانب التقنية للتجوال</h3>
    <ul>
        <li>تجوال الجيل الثاني (GSM) مدعوم من جميع المشغّلين ومتاح على كامل التراب تقريبًا.</li>
        <li>تجوال الجيل الثالث (UMTS) يعمل في المدن الرئيسية وعلى الطرق السريعة.</li>
        <li>تجوال الجيل الرابع (LTE) متاح رهنًا باتفاقية بين المشغّل الأصلي والمشغّل المغربي.</li>
        <li>تجوال VoLTE (الصوت عبر LTE) مدعوم من عدد محدود من أزواج المشغّلين.</li>
    </ul>


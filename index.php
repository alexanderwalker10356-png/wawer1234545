    <h2>История телеком-рынка Марокко</h2>

    <p>Марокканский телекоммуникационный рынок прошёл длительный путь трансформации. До конца 1990-х годов отрасль полностью контролировалась государством. Ключевым этапом стала реформа 1998 года, когда был принят закон о либерализации телекоммуникаций и создан независимый регулятор &mdash; Национальное агентство регулирования телекоммуникаций (ANRT). Этот шаг открыл рынок для частного капитала и конкуренции.</p>

    <p>Первым и на тот момент единственным оператором являлся Maroc Telecom, созданный на базе государственного монополиста Itissalat al-Maghrib. В 1999 году часть акций компании была приобретена международным инвестором, что ознаменовало начало приватизации сектора. Второй лицензией на предоставление услуг мобильной связи в 2000 году была наделена компания Médi Télécom, позднее переименованная в Orange Maroc. Третий оператор &mdash; Wana Corporate, работающий под брендом Inwi, &mdash; получил лицензию в 2009 году и быстро занял заметную долю рынка.</p>


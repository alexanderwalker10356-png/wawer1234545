    <h2>Технологии и стандарты связи</h2>

    <p>Марокко последовательно внедряло все основные поколения мобильной связи. Сети стандарта GSM (2G) были развёрнуты ещё в 1990-х годах и до сих пор обеспечивают базовое покрытие в отдалённых районах. Переход к 3G (UMTS/HSPA+) произошёл в 2007&ndash;2008 годах, а коммерческий запуск сетей 4G LTE состоялся в 2015 году.</p>

    <p>К 2024&ndash;2025 годам покрытие 4G LTE охватило подавляющее большинство населённых пунктов: крупные города, пригороды, туристические центры и основные автомагистрали. Параллельно операторы начали тестирование технологии 5G. Регулятор ANRT провёл процедуры распределения частотного ресурса в диапазонах, пригодных для развёртывания сетей пятого поколения, и первые пилотные зоны 5G появились в Касабланке и Рабате.</p>

    <div class="info-box">
        <p>Марокко использует европейские стандарты мобильной связи: GSM 900/1800 МГц для 2G, UMTS 2100 МГц для 3G и диапазоны 800/1800/2600 МГц для LTE. Это обеспечивает совместимость с большинством мобильных устройств, продаваемых в Европе и Азии.</p>

    <h1>Операторы мобильной связи в Марокко</h1>
    <p class="last-updated">Обновлено: октябрь 2026</p>

    <p>Рынок мобильной связи Марокко на протяжении более двух десятилетий формируется тремя операторами. Каждый из них занимает свою нишу, обладает собственной сетевой инфраструктурой и зоной покрытия. Ниже приведены подробные характеристики каждого оператора.</p>

    <div class="operator-section">
        <h2>Maroc Telecom (Itissalat al-Maghrib)</h2>

        <table class="spec-table">
            <tr><th>Основание</th><td>1998 (на базе государственного оператора, действовавшего с 1956 года)</td></tr>
            <tr><th>Владелец</th><td>Etisalat Group (мажоритарный пакет), Государство Марокко</td></tr>
            <tr><th>Технологии</th><td>2G (GSM 900/1800), 3G (UMTS 2100), 4G LTE (800/1800/2600 МГц), пилотный 5G</td></tr>
            <tr><th>Покрытие 4G</th><td>Более 90% населения</td></tr>
        </table>

        <p>Maroc Telecom &mdash; исторически первый и крупнейший телекоммуникационный оператор Марокко. Компания ведёт свою родословную от государственной почтово-телеграфной службы, существовавшей с момента обретения страной независимости. После реформы 1998 года оператор был преобразован в акционерное общество, а впоследствии частично приватизирован.</p>

        <p>Сегодня Maroc Telecom располагает самой разветвлённой сетевой инфраструктурой в стране. Базовые станции оператора установлены даже в труднодоступных горных районах Атласа и на окраинах Сахары, где другие операторы присутствуют лишь точечно. Сеть 4G LTE развёрнута во всех крупных и средних городах, а также вдоль ключевых автомагистралей, соединяющих Касабланку, Рабат, Фес, Марракеш, Танжер и Агадир.</p>

        <p>Компания также активно участвует в пилотных проектах 5G, проводя тестирование в Касабланке и Рабате. Помимо мобильной связи, Maroc Telecom владеет обширной фиксированной сетью и является ведущим интернет-провайдером страны. Оператор также расширил присутствие на африканском континенте, приобретя компании связи в нескольких странах Западной и Центральной Африки.</p>
    </div>

    <div class="operator-section">
        <h2>Orange Maroc</h2>

        <table class="spec-table">
            <tr><th>Основание</th><td>2000 (как Médi Télécom, ребрендинг в Orange Maroc в 2016 году)</td></tr>
            <tr><th>Владелец</th><td>Orange S.A. (Франция), финансовая группа Atlas Merchant Capital</td></tr>
            <tr><th>Технологии</th><td>2G (GSM 900/1800), 3G (UMTS 2100), 4G LTE (800/1800/2600 МГц), тестирование 5G</td></tr>
            <tr><th>Покрытие 4G</th><td>Более 85% населения</td></tr>
        </table>

        <p>Orange Maroc появился на рынке в 2000 году под названием Médi Télécom и стал первым конкурентом государственного монополиста. Компания была создана совместно испанскими и марокканскими инвесторами, а в 2010 году контроль перешёл к французской телеком-группе Orange, после чего произошёл ребрендинг.</p>

        <p>Оператор сфокусировал развитие сети на атлантическом побережье и крупнейших городских агломерациях. Покрытие 4G доступно в Касабланке, Рабате, Марракеше, Фесе, Танжере, Агадире, Мекнесе и десятках других городов. Вдоль основных автодорог между этими центрами также обеспечена связь четвёртого поколения.</p>

        <p>Orange Maroc инвестирует в модернизацию опорной сети и расширение ёмкости LTE в густонаселённых районах. Компания применяет технологию агрегации несущих (Carrier Aggregation) для увеличения пропускной способности в местах с высокой плотностью абонентов. В сельских районах покрытие обеспечивается преимущественно сетями 2G и 3G, хотя оператор постепенно расширяет присутствие LTE за пределами городов.</p>
    </div>

    <div class="operator-section">
        <h2>Inwi</h2>

        <table class="spec-table">
            <tr><th>Основание</th><td>2009 (мобильная лицензия; Wana Corporate основана в 2007 году)</td></tr>
            <tr><th>Владелец</th><td>Al Mada (марокканский инвестиционный холдинг)</td></tr>
            <tr><th>Технологии</th><td>2G (GSM 900/1800), 3G (UMTS 2100), 4G LTE (800/1800/2600 МГц), тестирование 5G</td></tr>
            <tr><th>Покрытие 4G</th><td>Более 75% населения</td></tr>
        </table>

        <p>Inwi &mdash; самый молодой мобильный оператор Марокко, вышедший на рынок в 2009 году после получения третьей лицензии на предоставление услуг мобильной связи. До этого материнская компания Wana Corporate предоставляла услуги фиксированной связи и беспроводного интернета на основе технологии CDMA.</p>

        <p>Несмотря на более позднее появление, Inwi быстро наращивал абонентскую базу и инфраструктуру. Оператор делает ставку на городские рынки, концентрируя инвестиции в наиболее густонаселённых регионах: Касабланка-Сеттат, Рабат-Сале-Кенитра, Марракеш-Сафи и Танжер-Тетуан-Аль-Хосейма. В этих регионах сеть 4G Inwi обеспечивает конкурентоспособное качество покрытия.</p>

        <p>В менее населённых регионах &mdash; на юге и востоке страны &mdash; покрытие Inwi ограничено преимущественно сетями 3G с точечным присутствием LTE в административных центрах провинций. Оператор компенсирует относительно меньший территориальный охват активным развитием ёмкости сети в городах и вложениями в высокоскоростной мобильный интернет. Inwi также принимает участие в программах тестирования 5G, проводимых под надзором регулятора ANRT.</p>
    </div>

